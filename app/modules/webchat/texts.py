def supported(lang: str | None) -> str | None:
    """'de-AT' → 'de', 'nb'/'nn' → 'no'; None for anything outside the eight."""
    if not lang:
        return None
    base = lang.strip().lower().replace("_", "-").split("-")[0]
    base = "no" if base in ("nb", "nn") else base
    return base if base in LANGUAGES else None


def from_accept_language(header: str | None) -> str | None:
    """The first supported language of an Accept-Language header, by its q-order."""
    items = []
    for i, part in enumerate((header or "").split(",")):
        tag, _, q = part.strip().partition(";q=")
        try:
            weight = float(q) if q else 1.0
        except ValueError:
            weight = 0.0
        items.append((-weight, i, tag))
    for _w, _i, tag in sorted(items):
        if (lang := supported(tag)) is not None:
            return lang
    return None


def pick(requested: str | None, accept_language: str | None, business: str | None) -> str:
    return supported(requested) or from_accept_language(accept_language) or supported(business) or "da"


def t(lang: str) -> dict[str, str]:
    return TEXTS.get(lang, TEXTS["da"])


def window_label(key: str, lang: str, weekday: int | None) -> str:
    """A call-back window's label (keys from app/modules/leads/callback.py) in `lang`."""
    x = t(lang)
    if key == "asap":
        return x["asap"]
    day, _, part = key.partition("_")
    when = x["today"] if day == "today" else (x["tomorrow"] if weekday is None else x["weekdays"].split("|")[weekday].capitalize())
    return f"{when} {x[part]}"
