// Generates src/i18n/messages/index.ts: static imports of every messages/<locale>/<ns>.json (bundlers need static
// paths). Run after adding a namespace: `node scripts/i18n-index.mjs`. CI checks that the file is up to date.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../src/i18n/messages/", import.meta.url).pathname;
const locales = readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
let imports = "";
let body = "";
for (const l of locales) {
  const files = readdirSync(join(dir, l)).filter((f) => f.endsWith(".json")).sort();
  body += `  ${l}: {\n`;
  for (const f of files) {
    const ns = f.replace(/\.json$/, "");
    const id = `${l}_${ns}`.replace(/[^a-zA-Z0-9_]/g, "_");
    imports += `import ${id} from "./${l}/${f}";\n`;
    body += `    ${ns}: ${id},\n`;
  }
  body += "  },\n";
}
writeFileSync(join(dir, "index.ts"),
  `// Generated by scripts/i18n-index.mjs – do not edit.\n${imports}\nexport const MESSAGES: Record<string, Record<string, Record<string, unknown>>> = {\n${body}};\n`);
console.log(`wrote messages/index.ts (${locales.length} locales)`);
